// Product tile icon from the name / allergens (shown when no product image is available).
export function productIcon(name: string, contains: string[] = []): IconName {
  const n = name.toLowerCase();
  if (/bouillon|stock|fond|liemi/.test(n)) return "soup";
  if (contains.includes("fish") || /salmon|trout|lohi|fish|kala|siika/.test(n))
    return "fish";
  if (/berry|mustikka|blueberr|lingon|puolukka/.test(n)) return "cherry";
  if (/egg|muna/.test(n)) return "egg";
  if (/potato|peruna|carrot|porkkana|onion|sipuli/.test(n)) return "carrot";
  if (/leek|dill|tilli|herb|purjo|parsley/.test(n)) return "sprout";
  if (/bread|pastry|flour|leipä|rye|ruis|crisp/.test(n)) return "wheat";
  if (
    contains.includes("milk") ||
    /milk|cream|kerma|sauce|butter|cheese|quark|rahka|maito|voi/.test(n)
  )
    return "milk";
  return "package";
}
export function dishIcon(name: string): IconName {
  const n = name.toLowerCase();
  if (/croissant/.test(n)) return "croissant";
  if (/chips|crisps|candy|candies|sweets|snacks/.test(n)) return "candy";
  if (/drinks|soda|juice|water/.test(n)) return "cup-soda";
  if (/fruits?|apple|banana|orange/.test(n)) return "apple";
  if (/soup|keitto/.test(n)) return "soup";
  if (/bread|sandwich|leipä/.test(n)) return "wheat";
  if (/pie|cake|dessert|piirakka/.test(n)) return "cherry";
  if (/fish|salmon/.test(n)) return "fish";
  if (/salad|vegetables|vegan|vegetarian/.test(n)) return "leaf";
  return "utensils";
}
